def _as_dict(val: Any) -> Dict[str, Any]:
    return val if isinstance(val, dict) else {}


def _as_list(val: Any) -> List[Any]:
    return val if isinstance(val, list) else []


def _fmt_bytes(num: Any) -> str:
    try:
        b = float(num or 0)
    except (TypeError, ValueError):
        return "0 B"
    for unit in ("B", "KB", "MB", "GB"):
        if b < 1024 or unit == "GB":
            return f"{b:.1f} {unit}" if unit != "B" else f"{int(b)} B"
        b /= 1024.0
    return f"{b:.1f} GB"


def _infer_tech_stack(
    primary_lang: str,
    languages: List[Tuple[str, float, str]],
    config_files: List[Dict[str, str]],
    files: List[Dict[str, str]],
    readme_text: str,
) -> List[Tuple[str, str, str]]:
    """Detect languages, frameworks, databases, and tooling used in the repo."""
    stack: List[Tuple[str, str, str]] = []
    seen = set()

    def add_item(layer: str, tech: str, evidence: str) -> None:
        key = (layer, tech.lower())
        if key not in seen:
            seen.add(key)
            stack.append((layer, tech, evidence))

    if primary_lang and primary_lang != "—":
        add_item("Core Language", primary_lang, "Primary repository language")

    for lang_name, pct, disp in languages:
        add_item("Language Mix", lang_name, f"{disp} of detected codebase")

    blob = " ".join(
        [
            readme_text.lower(),
            " ".join(f.get("name", "").lower() for f in files),
            " ".join(c.get("path", "").lower() for c in config_files),
        ]
    )

    signatures = [
        ("Web / API Framework", "Flask", ("flask", "app.py")),
        ("Web / API Framework", "FastAPI / Uvicorn", ("fastapi", "uvicorn")),
        ("Frontend UI", "React + Vite", ("react", "vite.config", ".jsx", ".tsx")),
        ("Styling", "Tailwind CSS", ("tailwind",)),
        ("Database / Storage", "SQLite", (".db", "sqlite", "init_db.py")),
        ("Database / Storage", "PostgreSQL / SQLAlchemy", ("postgres", "sqlalchemy", "models.py")),
        ("AI / LLM Integration", "Google Gemini API", ("gemini", "google-generativeai", "genai")),
        ("AI / LLM Integration", "Anthropic / OpenAI SDK", ("anthropic", "openai")),
        ("Container & DevOps", "Docker / CI Pipeline", ("dockerfile", "docker-compose", ".github/workflows")),
        ("Package Management", "Python pip / Requirements", ("requirements.txt", "pyproject.toml")),
        ("Package Management", "Node / npm", ("package.json", "package-lock.json")),
    ]

    for layer, tech, tokens in signatures:
        matched = [t for t in tokens if t in blob]
        if matched:
            add_item(layer, tech, f"Detected via {', '.join(matched[:2])}")

    for cfg in config_files[:8]:
        path = cfg.get("path") or ""
        desc = cfg.get("description") or cfg.get("category") or "Configuration file"
        if path:
            add_item("Configuration", path, desc)

    if not stack:
        add_item("Runtime", primary_lang or "General Software", "Standard repository layout")

    return stack


def _extract_context(payload: Dict[str, Any]) -> Dict[str, Any]:
    """Normalize DevFlow /analyze + /analyze/insights payload into rich report sections."""
    data = _as_dict(payload)
    repo = _as_dict(data.get("repository")) or data
    stats = _as_dict(data.get("stats"))
    arch = _as_dict(data.get("architecture"))
    analytics = _as_dict(data.get("analytics"))
    readme_obj = _as_dict(data.get("readme"))

    full_name = str(repo.get("full_name") or repo.get("name") or "Repository")
    owner = str(repo.get("owner") or (full_name.split("/")[0] if "/" in full_name else "Owner"))
    description = str(
        repo.get("description")
        or "Comprehensive technical architecture, stack, and codebase assessment generated by DevFlow."
    )
    primary_lang = str(repo.get("primary_language") or repo.get("language") or "—")
    default_branch = str(repo.get("default_branch") or "main")
    visibility = str(repo.get("visibility") or "public").capitalize()
    license_name = str(repo.get("license") or "Not specified")
    html_url = str(repo.get("html_url") or f"https://github.com/{full_name}")
    size_kb = repo.get("size_kb") or 0

    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    # 6 Core KPIs matching DevFlow UI
    total_files = stats.get("total_files", len(_as_list(data.get("files"))))
    total_dirs = stats.get("total_directories", len(_as_list(data.get("top_level_directories"))))
    max_depth = stats.get("max_depth", 1)

    kpis = [
        ("Stars", str(repo.get("stars", 0))),
        ("Forks", str(repo.get("forks", 0))),
        ("Open Issues", str(repo.get("open_issues", 0))),
        ("Contributors", str(repo.get("contributors", 1))),
        ("Files Analyzed", str(total_files)),
        ("Max Depth", f"{max_depth} lvl"),
    ]

    # Language stats (DevFlow sends `language_stats`: [{name, percent, bytes}])
    languages: List[Tuple[str, float, str]] = []
    for item in _as_list(data.get("language_stats")):
        if isinstance(item, dict):
            name = str(item.get("name") or item.get("language") or "Unknown")
            pct = float(item.get("percent") or item.get("percentage") or 0.0)
            b_str = _fmt_bytes(item.get("bytes")) if item.get("bytes") is not None else f"{pct:.1f}%"
            languages.append((name, pct, f"{pct:.1f}% ({b_str})"))
    if not languages and primary_lang != "—":
        languages.append((primary_lang, 100.0, "100.0%"))

    # Composition
    composition_rows: List[Tuple[str, str, str]] = []
    for item in _as_list(data.get("composition")):
        if isinstance(item, dict):
            cat = str(item.get("category") or "Other").replace("_", " ").title()
            cnt = int(item.get("count") or 0)
            sz = _fmt_bytes(item.get("size_bytes") or 0)
            composition_rows.append((cat, f"{cnt:,} files", sz))

    # File types
    file_type_rows: List[Tuple[str, str, str]] = []
    for item in _as_list(data.get("file_types"))[:12]:
        if isinstance(item, dict):
            lbl = str(item.get("label") or item.get("extension") or "File")
            ext = str(item.get("extension") or "")
            cnt = int(item.get("count") or 0)
            file_type_rows.append((lbl, ext or "—", f"{cnt:,}"))

    # Top-level directories
    dir_rows: List[Tuple[str, str, str]] = []
    for item in _as_list(data.get("top_level_directories"))[:12]:
        if isinstance(item, dict):
            d_name = str(item.get("name") or "/")
            f_cnt = int(item.get("file_count") or 0)
            sz = _fmt_bytes(item.get("size_bytes") or 0)
            dir_rows.append((d_name, f"{f_cnt:,} files", sz))

    # Root files & config files
    root_files: List[Dict[str, str]] = []
    for item in _as_list(data.get("files"))[:30]:
        if isinstance(item, dict):
            root_files.append(
                {
                    "name": str(item.get("name") or item.get("path") or ""),
                    "type": "Directory" if item.get("type") == "dir" else "File",
                    "size": _fmt_bytes(item.get("size") or item.get("size_bytes") or 0),
                }
            )

    config_files: List[Dict[str, str]] = []
    for item in _as_list(data.get("config_files"))[:15]:
        if isinstance(item, dict):
            config_files.append(
                {
                    "path": str(item.get("path") or ""),
                    "category": str(item.get("category") or "Config").title(),
                    "description": str(item.get("description") or "Project configuration file"),
                }
            )

    readme_content = str(readme_obj.get("content") or "").strip()
    readme_lines = [ln.strip() for ln in readme_content.splitlines() if ln.strip()][:28]

    # Architecture summary & layers
    arch_summary = str(
        arch.get("summary")
        or arch.get("overview")
        or (
            f"{full_name} is organized around a {primary_lang} codebase comprising {total_files} analyzed files "
            f"across {total_dirs} directories (maximum nesting depth: {max_depth})."
        )
    )
    arch_modules: List[Tuple[str, str, str]] = []
    for node in _as_list(arch.get("nodes"))[:12]:
        if isinstance(node, dict):
            arch_modules.append(
                (
                    str(node.get("label") or node.get("id") or "Module"),
                    str(node.get("layer") or "Core").title(),
                    str(node.get("summary") or node.get("path") or "Application component"),
                )
            )
    if not arch_modules:
        for rf in root_files[:8]:
            fname = rf["name"]
            layer = (
                "Entry / Routing"
                if any(k in fname.lower() for k in ("app.", "main.", "index.", "server."))
                else "Data / Persistence"
                if any(k in fname.lower() for k in ("db", "model", "schema", "sql"))
                else "Documentation / Config"
                if any(k in fname.lower() for k in ("readme", "json", "yml", "toml", "txt", "md"))
                else "Core Logic"
            )
            arch_modules.append((fname, layer, f"{rf['type']} in repository root ({rf['size']})"))

    tech_stack = _infer_tech_stack(primary_lang, languages, config_files, root_files, readme_content)

    # Analytics metrics
    est_loc = analytics.get("estimated_loc") or analytics.get("loc") or max(int(size_kb) * 18, total_files * 85)

    return {
        "full_name": full_name,
        "owner": owner,
        "description": description,
        "primary_lang": primary_lang,
        "default_branch": default_branch,
        "visibility": visibility,
        "license": license_name,
        "html_url": html_url,
        "size_kb": size_kb,
        "total_files": total_files,
        "total_dirs": total_dirs,
        "max_depth": max_depth,
        "est_loc": est_loc,
        "generated_at": generated_at,
        "kpis": kpis,
        "languages": languages,
        "composition_rows": composition_rows,
        "file_type_rows": file_type_rows,
        "dir_rows": dir_rows,
        "root_files": root_files,
        "config_files": config_files,
        "readme_lines": readme_lines,
        "arch_summary": arch_summary,
        "arch_modules": arch_modules,
        "tech_stack": tech_stack,
    }


